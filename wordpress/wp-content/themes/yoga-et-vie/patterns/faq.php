<div class="wp-block-group" style="margin-top:var(--wp--preset--spacing--40)"><!-- wp:details -->
<details class="wp-block-details"><summary>Faut-il être souple pour faire du yoga ?</summary><!-- wp:paragraph -->
<p>Non. La souplesse n’est pas un prérequis : chacun pratique avec son corps tel qu’il est aujourd’hui, et les postures sont adaptées à chacun.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Je n’ai jamais pratiqué : puis-je rejoindre un cours ?</summary><!-- wp:paragraph -->
<p>Oui, les débutants sont les bienvenus. Signalez-le simplement à l’enseignant·e en arrivant. Les modalités d’un éventuel cours d’essai sont à confirmer par l’association.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Que faut-il apporter ?</summary><!-- wp:paragraph -->
<p>Une tenue souple et confortable, une petite couverture pour la relaxation et une bouteille d’eau. Pour le tapis : information à confirmer (prêt possible ou tapis personnel).</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Le yoga est-il adapté en cas de problème de santé ?</summary><!-- wp:paragraph -->
<p>Le yoga se pratique à tout âge, mais il ne remplace pas un avis médical. En cas de doute, de grossesse, de douleur ou de pathologie, demandez conseil à votre médecin et prévenez l’enseignant·e, qui adaptera la pratique si besoin.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

